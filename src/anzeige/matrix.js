export const ZEICHENBREITE = 6; // fünf Punkte und eine Lücke
export const ZEILENHOEHE = 9; // sieben Punkte und zwei für Unterlängen

const MUSTER = {};
for (const [zeichen, bild] of Object.entries(ZEICHEN)) MUSTER[zeichen] = bild.split(' ');

export function hatZeichen(zeichen) {
  return MUSTER[zeichen] !== undefined;
}

// Breite eines Texts in Punkten, ohne die Lücke nach dem letzten Zeichen
export function textBreite(text) {
  return Math.max(0, [...text].length * ZEICHENBREITE - 1);
}

// Ein Punktfeld: spalten mal zeilen, jeder Punkt an oder aus.
export function neuesPunktfeld(spalten, zeilen) {
  return { spalten, zeilen, an: new Uint8Array(spalten * zeilen) };
}

export function schreibe(feld, text, spalte, zeile) {
  let x = spalte;
  for (const zeichen of text) {
    const muster = MUSTER[zeichen] || MUSTER['?'];
    for (let r = 0; r < muster.length; r++) {
      for (let c = 0; c < 5; c++) {
        const px = x + c;
        const py = zeile + r;
        if (muster[r][c] === '#' && px >= 0 && px < feld.spalten && py >= 0 && py < feld.zeilen) {
          feld.an[py * feld.spalten + px] = 1;
        }
      }
    }
    x += ZEICHENBREITE;
  }
}

export function schreibeMittig(feld, text, zeile) {
  schreibe(feld, text, Math.round((feld.spalten - textBreite(text)) / 2), zeile);
}

// Zeichnet das Punktfeld. raster ist der Abstand der Punkte in Pixeln.
// dunkel ist die Farbe der unbeleuchteten Punkte, null lässt sie weg.
export function zeichnePunktfeld(stift, feld, x, y, raster, hell, dunkel) {
  const r = raster * 0.38;
  for (const durchgang of dunkel ? [0, 1] : [1]) {
    stift.fillStyle = durchgang ? hell : dunkel;
    stift.beginPath();
    for (let py = 0; py < feld.zeilen; py++) {
      for (let px = 0; px < feld.spalten; px++) {
        if (feld.an[py * feld.spalten + px] !== durchgang) continue;
        const cx = x + (px + 0.5) * raster;
        const cy = y + (py + 0.5) * raster;
        stift.moveTo(cx + r, cy);
        stift.arc(cx, cy, r, 0, Math.PI * 2);
      }
    }
    stift.fill();
  }
}
